// Helper to inject keys into a dictionary block in I18nStore.ts
function injectIntoDict(dictName, langKey) {
  const marker = `export const ${dictName}: Record<string, string> = {`;
  const idx = content.indexOf(marker);
  if (idx === -1) {
    throw new Error(`Cannot find dictionary: ${dictName}`);
  }
  const endIdx = content.indexOf('};', idx);
  if (endIdx === -1) {
    throw new Error(`Cannot find closing brace for: ${dictName}`);
  }

  const existingBlock = content.slice(idx, endIdx);
  const langObj = newKeys[langKey];
  let additions = '\n  // Added Map, SOS, Battery and System Keys\n';
  for (const [k, v] of Object.entries(langObj)) {
    // Escape single quotes if any
    const escaped = v.replace(/'/g, "\\'");
    additions += `  ${k}: '${escaped}',\n`;
  }

  // Prepend or append inside existingBlock before closing '};'
  const newBlock = content.slice(0, endIdx).trimEnd() + ',\n' + additions.trimEnd() + '\n};' + content.slice(endIdx + 2);
  content = newBlock;
}

